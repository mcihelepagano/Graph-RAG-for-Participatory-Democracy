PAIRWISE_SYSTEM = """You are an expert debate research analyst.
You will see two debate summaries for the same policy.

Decide which summary is more valuable for a researcher who needs to
understand the debate landscape and write a balanced contribution.
Evaluate on coverage, balance, insight, and specificity.

Reply with EXACTLY ONE LETTER: "A" or "B" on the first line.
Then one sentence justification. No other text."""


def judge_pair(policy, summary_a, summary_b, retries=2):
    user = (f'Policy: "{policy}"\n\nSUMMARY A:\n{summary_a}\n\n'
            f"SUMMARY B:\n{summary_b}\n\n"
            'Reply with ONLY "A" or "B" on the first line, then one sentence.')
    for attempt in range(retries + 1):
        try:
            r = ollama.chat(
                model=JUDGE_MODEL,
                messages=[{"role": "system", "content": PAIRWISE_SYSTEM},
                          {"role": "user", "content": user}],
                options={"temperature": 0.0, "num_predict": 100,
                         "num_ctx": 8192})
            ans = parse_ab(r["message"]["content"])
            if ans is not None:
                return ans
            time.sleep(1)
        except Exception as e:
            print(f"      pairwise error (try {attempt+1}): {e}")
            time.sleep(2)
    return None


def double_sided(policy, summary_b, summary_ch):
    r1 = judge_pair(policy, summary_b, summary_ch); time.sleep(SLEEP_SEC)
    r2 = judge_pair(policy, summary_ch, summary_b); time.sleep(SLEEP_SEC)
    bw = cw = 0
    if r1 == "A": bw += 1
    elif r1 == "B": cw += 1
    if r2 == "B": bw += 1
    elif r2 == "A": cw += 1
    winner = "system_b" if bw > cw else ("challenger" if cw > bw else "tie")
    return {"winner": winner, "b_wins": bw, "ch_wins": cw,
            "run1": r1, "run2": r2}


