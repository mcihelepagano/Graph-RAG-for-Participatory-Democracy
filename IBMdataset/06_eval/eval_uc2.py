# METRIC 1 — Coverage (NLI entailment)
# ============================================================
def compute_coverage(summary_text, args):
    if not args:
        return None
    probs  = nli_label_batch([summary_text] * len(args), args)
    entail = [p[1] for p in probs]
    return sum(1 for e in entail if e > ENTAIL_THRESH) / len(args)


# ============================================================
# METRIC 4 — Stance balance (NEW)
# ============================================================
def stance_balance(summary_text, pros, cons):
    """How evenly the summary covers PRO vs CON material.

    Uses NLI entailment: count how many PRO args and how many CON args
    the summary entails. balance = 1 - |pro_frac - 0.5| * 2, where
    pro_frac = covered_pros / (covered_pros + covered_cons).

    1.0 = perfectly balanced; 0.0 = entirely one-sided.
    Directly operationalises the thesis goal of balanced contributions.
    """
    if not pros or not cons:
        return None
    args   = pros + cons
    labels = ["pro"] * len(pros) + ["con"] * len(cons)
    probs  = nli_label_batch([summary_text] * len(args), args)
    entail = [p[1] for p in probs]
    cov_p = sum(1 for e, l in zip(entail, labels)
                if l == "pro" and e > ENTAIL_THRESH)
    cov_c = sum(1 for e, l in zip(entail, labels)
                if l == "con" and e > ENTAIL_THRESH)
    if cov_p + cov_c == 0:
        return 0.0
    pro_frac = cov_p / (cov_p + cov_c)
    return 1.0 - abs(pro_frac - 0.5) * 2.0


