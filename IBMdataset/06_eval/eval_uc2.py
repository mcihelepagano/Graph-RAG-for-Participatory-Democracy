def build_format_comparison(format_summaries):
    """Side-by-side tie rates: structured vs paragraph."""
    print("\n=== FORMAT COMPARISON: structured vs paragraph ===")
    comparison = {"chosen_k": CHOSEN_K, "per_challenger": {}}
    for ch in CHALLENGERS:
        entry = {}
        for fmt_name in FORMATS:
            if fmt_name not in format_summaries:
                continue
            m = format_summaries[fmt_name]["per_system"].get(ch, {})
            entry[fmt_name] = {
                "tie_rate": m.get("pairwise_tie_rate"),
                "b_winrate": m.get("pairwise_b_winrate"),
            }
        if "structured" in entry and "paragraph" in entry:
            st = entry["structured"]["tie_rate"]
            pt = entry["paragraph"]["tie_rate"]
            if st is not None and pt is not None:
                entry["tie_rate_drop"] = round(st - pt, 4)
        comparison["per_challenger"][ch] = entry
    save_json(comparison, F_COMPARE)

    try:
        from tabulate import tabulate
    except ImportError:
        tabulate = None
    headers = ["Challenger", "Structured ties", "Paragraph ties", "Drop"]
    rows = []
    for ch, e in comparison["per_challenger"].items():
        st = e.get("structured", {}).get("tie_rate")
        pt = e.get("paragraph", {}).get("tie_rate")
        drop = e.get("tie_rate_drop")
        rows.append([ch,
                     f"{st*100:.0f}%" if st is not None else "-",
                     f"{pt*100:.0f}%" if pt is not None else "-",
                     f"{drop*100:+.1f}pp" if drop is not None else "-"])
    if tabulate:
        print(tabulate(rows, headers=headers, tablefmt="grid"))
    else:
        print(headers); [print(r) for r in rows]
    return comparison


