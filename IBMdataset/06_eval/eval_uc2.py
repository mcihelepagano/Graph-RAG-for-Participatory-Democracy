def build_format_summary(fmt_name, summaries, coverage, balance,
                         bertscore, faith, rubric, pairwise):
    out = {"format": fmt_name, "chosen_k": CHOSEN_K,
           "judge_model": JUDGE_MODEL, "per_system": {}}

    for system in SYSTEMS:
        cov_m, cov_s = mean_std(list(coverage.get(system, {}).values()))
        bal_m, bal_s = mean_std(list(balance.get(system, {}).values()))
        bs_pp = bertscore.get(system, {}).get("per_policy", {})
        bs_m, bs_s   = mean_std(list(bs_pp.values()))

        f_scores = [v["faithfulness"]
                    for v in faith.get(system, {}).get("per_policy", {}).values()
                    if "faithfulness" in v]
        f_m, f_s = mean_std(f_scores)

        r_pp = rubric.get(system, {}).get("per_policy", {})
        rubric_means = {}
        for kk in RUBRIC_KEYS:
            vals = [v[kk] for v in r_pp.values() if v.get(kk) is not None]
            rubric_means[f"rubric_{kk}"], _ = mean_std(vals)

        entry = {
            "coverage_mean": cov_m, "coverage_std": cov_s,
            "faithfulness_mean": f_m, "faithfulness_std": f_s,
            "bertscore_f1_mean": bs_m, "bertscore_f1_std": bs_s,
            "stance_balance_mean": bal_m, "stance_balance_std": bal_s,
            "n_summaries": len(summaries.get(system, {})),
            **rubric_means,
        }
        if system != "System B":
            pw = pairwise.get(system, {})
            entry.update({
                "pairwise_b_wins": pw.get("b_wins"),
                "pairwise_ch_wins": pw.get("ch_wins"),
                "pairwise_ties": pw.get("ties"),
                "pairwise_total": pw.get("total"),
                "pairwise_b_winrate": pw.get("b_winrate"),
                "pairwise_tie_rate": pw.get("tie_rate"),
            })
        out["per_system"][system] = entry
    return out


def write_format_csv(summary, path):
    rows = [{"system": s, **m} for s, m in summary["per_system"].items()]
    keys = []
    for r in rows:
        for k in r:
            if k not in keys:
                keys.append(k)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k) for k in keys})
    print(f"  wrote {path}")


