# RUBRIC JUDGE (NEW)
# ============================================================
RUBRIC_SYSTEM = """You are an expert debate research analyst scoring ONE
debate summary.

Score the summary on each criterion from 1 (poor) to 5 (excellent).
Score each criterion independently and use the full range.

  coverage    : does it capture the main dimensions of the debate?
  balance     : does it fairly represent both PRO and CON perspectives?
  insight     : does it identify the key tension and missing perspectives?
  specificity : are the claims concrete rather than vague?

Return ONLY this JSON, no markdown:
{"coverage": 1-5, "balance": 1-5, "insight": 1-5, "specificity": 1-5}"""

RUBRIC_KEYS = ["coverage", "balance", "insight", "specificity"]


def judge_rubric(policy, summary_text, retries=2):
    user = (f'Policy: "{policy}"\n\nSUMMARY:\n{summary_text}\n\n'
            "Score the summary on the four criteria. Return only the JSON.")
    for attempt in range(retries + 1):
        try:
            r = ollama.chat(
                model=JUDGE_MODEL,
                messages=[{"role": "system", "content": RUBRIC_SYSTEM},
                          {"role": "user", "content": user}],
                options={"temperature": 0.0, "num_predict": 200,
                         "num_ctx": 8192})
            obj = parse_json_object(r["message"]["content"],
                                    required_keys=RUBRIC_KEYS)
            if obj is not None:
                clean = {}
                for kk in RUBRIC_KEYS:
                    try:
                        v = float(obj[kk])
                    except (ValueError, TypeError):
                        v = None
                    clean[kk] = v if (v is not None and 1 <= v <= 5) else None
                if all(clean[kk] is not None for kk in RUBRIC_KEYS):
                    return clean
            time.sleep(1)
        except Exception as e:
            print(f"      rubric error (try {attempt+1}): {e}")
            time.sleep(2)
    return None


