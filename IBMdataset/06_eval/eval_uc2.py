"""
eval_uc2.py
===========
Stage 2 evaluation for UC2 (debate summarization) at pool=200, k=15.

REPLACES stage2_eval_uc2.py. It also absorbs the SimpleRAG / paragraph
ablation that was previously a separate script (stage2_eval_uc2_paragraph.py),
because the two scripts shared ~80% of their code. Output format is
selectable via the FORMATS list below.

Key changes from the original pipeline:

  CHANGE 1 — RUBRIC JUDGE added alongside the binary pairwise.
    The binary pairwise produced 76-100% tie rates with the structured
    format because a forced A/B choice cannot express small quality
    differences. The rubric judge scores each summary independently
    1-5 on four named criteria. Ties then occur only on genuine
    equality. This is the ConQRet / G-Eval approach.

  CHANGE 2 — STANCE BALANCE metric (NEW).
    The thesis goal is helping citizens write BALANCED contributions,
    but no metric measured balance directly. stance_balance() measures
    how evenly the summary's content is split between PRO and CON
    material, using NLI entailment of pro vs con source arguments.
    1.0 = perfectly balanced, 0.0 = entirely one-sided.

  CHANGE 3 — both output formats in one script.
    FORMATS = ["structured", "paragraph"]. The paragraph run is the
    ablation that tests whether the structured 5-field template was
    causing the high tie rate. Tie rates for both are reported
    side by side.

  CHANGE 4 — shared code, corrected 28-policy list.

METRICS
  1. Coverage     — fraction of retrieved args entailed by the summary
                    (NLI). Fabbri SummEval 2021; RAGAS 2024.
  2. Faithfulness — fraction of summary claims supported by sources
                    (LLM claim verification). Liu G-Eval 2023; RAGAS.
  3. BERTScore F1 — vs k=15 reference summary. Zhang et al. 2020.
  4. Stance balance — PRO/CON evenness of summary content (NEW).
  5. Rubric judge — 1-5 on coverage, balance, insight, specificity.
  6. Binary pairwise — System B vs challengers, double-sided.

INPUT
  Structured summaries : results/sweep_uc2/summaries/<system>_k15.json
  Paragraph + SimpleRAG: generated by this script if missing
  data/uc2_reference_summaries.json
  data/neo4j_export_full.json   (for SimpleRAG corpus)
  results/sweep_uc2/retrieval/<system>_k15.json

OUTPUT
  results/eval_uc2/<format>/
    faithfulness.json  coverage.json  bertscore.json
    stance_balance.json  rubric_scores.json  pairwise.json
    summary.json  summary.csv
  results/eval_uc2/format_comparison.json

Usage:
    python eval_uc2.py
"""

