# METRIC 3 — BERTScore F1
# ============================================================
def render_reference(ref_fields):
    return (f"STRONGEST PRO: {ref_fields.get('STRONGEST_PRO', '')}\n"
            f"STRONGEST CON: {ref_fields.get('STRONGEST_CON', '')}\n"
            f"KEY TENSION: {ref_fields.get('KEY_TENSION', '')}\n"
            f"MISSING PERSPECTIVES: {ref_fields.get('MISSING_PERSPECTIVES', '')}\n"
            f"OVERALL BALANCE: {ref_fields.get('OVERALL_BALANCE', '')}")


def compute_bertscore(candidates, references):
    """BERTScore F1 per (candidate, reference) pair. Falls back to
    embedding cosine similarity if bert_score is not installed."""
    try:
        from bert_score import score as bs_score
        _, _, F1 = bs_score(candidates, references, lang="en",
                            verbose=False,
                            model_type="microsoft/deberta-xlarge-mnli")
        return F1.tolist(), "bertscore"
    except ImportError:
        print("  WARNING: bert_score not installed — using cosine proxy. "
              "Install with: pip install bert-score")
        c = embed_texts(candidates)
        r = embed_texts(references)
        return [float(np.dot(ci, ri)) for ci, ri in zip(c, r)], "cosine_proxy"


