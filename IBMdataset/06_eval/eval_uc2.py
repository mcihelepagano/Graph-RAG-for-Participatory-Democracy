STRUCTURED_SYSTEM = """You are an expert debate summarizer.
Analyze the provided policy topic and the retrieved PRO and CON arguments.
Generate a structured debate summary strictly as a JSON object.
You must use exactly these 5 keys:
{
  "STRONGEST_PRO": "...",
  "STRONGEST_CON": "...",
  "KEY_TENSION": "...",
  "MISSING_PERSPECTIVES": "...",
  "OVERALL_BALANCE": "..."
}
Be specific. KEY_TENSION must name the contradicting CLAIMS, not just the topic."""

PARAGRAPH_SYSTEM = """You are an expert debate summarizer.

You will receive a policy topic and a set of PRO and CON arguments retrieved
from a debate corpus. Write a single coherent paragraph (150-200 words) that
covers, in flowing prose, all of the following:
  (a) the strongest PRO claim and the reasoning behind it,
  (b) the strongest CON claim and the reasoning behind it,
  (c) the central tension — name the specific contradicting claims,
  (d) what perspectives seem missing from the arguments,
  (e) an overall assessment of whether the debate is well-balanced.

Do NOT use headers, bullet points, or labels. Write natural prose only.
Be specific. Start directly with substance, no preamble, no markdown."""


def render_structured(fields):
    return (f"STRONGEST PRO: {fields['STRONGEST_PRO']}\n"
            f"STRONGEST CON: {fields['STRONGEST_CON']}\n"
            f"KEY TENSION: {fields['KEY_TENSION']}\n"
            f"MISSING PERSPECTIVES: {fields['MISSING_PERSPECTIVES']}\n"
            f"OVERALL BALANCE: {fields['OVERALL_BALANCE']}")


def generate_summary(fmt_name, policy, pros, cons, retries=2):
    user = (f"Policy Topic: {policy}\n\n"
            f"PRO ARGUMENTS:\n" + "\n".join(f"- {a}" for a in pros) +
            f"\n\nCON ARGUMENTS:\n" + "\n".join(f"- {a}" for a in cons))
    for attempt in range(retries + 1):
        try:
            if fmt_name == "structured":
                r = ollama.chat(
                    model=SUMMARIZER,
                    messages=[{"role": "system", "content": STRUCTURED_SYSTEM},
                              {"role": "user", "content": user}],
                    format="json",
                    options={"temperature": 0.0, "num_predict": 1000,
                             "num_ctx": 8192})
                obj = parse_json_object(r["message"]["content"],
                                        required_keys=REF_KEYS)
                if obj is not None:
                    return render_structured(obj)
            else:  # paragraph
                r = ollama.chat(
                    model=SUMMARIZER,
                    messages=[{"role": "system", "content": PARAGRAPH_SYSTEM},
                              {"role": "user",
                               "content": user + "\n\nWrite the paragraph now."}],
                    options={"temperature": 0.0, "num_predict": 500,
                             "num_ctx": 8192})
                text = re.sub(r"<think(ing)?>.*?</think(ing)?>", "",
                              r["message"]["content"], flags=re.DOTALL)
                text = re.sub(r"```", "", text).strip()
                if len(text.split()) >= 50:
                    return text
            time.sleep(1)
        except Exception as e:
            print(f"      summary error (try {attempt+1}): {e}")
            time.sleep(2)
    return None


def ensure_summaries(fmt_name, k):
    """Return {system: {policy: record}} of summaries for a given format.

    For structured: reuses the existing sweep summaries where present.
    For paragraph: generates them. SimpleRAG always generated here.
    """
    print(f"\n  Ensuring {fmt_name} summaries (k={k})...")
    summ_dir = os.path.join(OUT_ROOT, fmt_name, "summaries")
    os.makedirs(summ_dir, exist_ok=True)

    all_summaries = {}
    for system in SYSTEMS:
        safe = system.lower().replace(" ", "_")
        out_path = os.path.join(summ_dir, f"{safe}_k{k}.json")

        # Fast path: reuse original structured sweep summaries
        if fmt_name == "structured" and system != "SimpleRAG":
            sweep_path = os.path.join(SWEEP_SUMM, f"{safe}_k{k}.json")
            if os.path.exists(sweep_path) and not os.path.exists(out_path):
                save_json(load_json(sweep_path), out_path)

        existing = load_checkpoint(out_path)

        # Retrievals for this system
        if system == "SimpleRAG":
            retr_map = ensure_simplerag_retrieval(k)
        else:
            rp = os.path.join(SWEEP_RETR, f"{safe}_k{k}.json")
            if not os.path.exists(rp):
                raise FileNotFoundError(f"Missing retrieval: {rp}")
            retr_map = {r["policy"]: r for r in load_json(rp)}

        for policy in POLICIES:
            if policy in existing:
                continue
            if policy not in retr_map:
                continue
            pros = retr_map[policy].get("retrieved_pros", [])
            cons = retr_map[policy].get("retrieved_cons", [])
            if not pros and not cons:
                continue
            text = generate_summary(fmt_name, policy, pros, cons)
            if text is None:
                print(f"      failed: {policy[:45]}")
                continue
            existing[policy] = {"summary_text": text,
                                "retrieved_pros": pros,
                                "retrieved_cons": cons,
                                "format": fmt_name, "system": system}
            save_json(existing, out_path)
            time.sleep(SLEEP_SEC)

        all_summaries[system] = existing
        print(f"    {system}: {len(existing)} summaries")
    return all_summaries


