# METRIC 2 — Faithfulness (LLM claim verification)
# ============================================================
FAITH_SYSTEM = """You are a meticulous fact-checker.
You will see (1) a SUMMARY of a policy debate and (2) the SOURCE arguments
the summary is supposedly based on.

Extract every distinct factual or argumentative claim from the summary, and
decide for each whether it is SUPPORTED by the source arguments (directly
stated or clearly entailed). Skip mere framing statements — only substantive
claims about pros, cons, tensions, or perspectives.

Output STRICT JSON, nothing else:
{
  "claims": [
    {"claim": "...", "supported": true|false},
    ...
  ]
}"""


def judge_faithfulness(summary_text, pros, cons, retries=2):
    user = (f"SUMMARY:\n{summary_text}\n\nSOURCE ARGUMENTS:\nPROS:\n" +
            "\n".join(f"  - {p}" for p in pros) + "\n\nCONS:\n" +
            "\n".join(f"  - {c}" for c in cons) +
            "\n\nExtract claims and mark each supported / unsupported.")
    for attempt in range(retries + 1):
        try:
            r = ollama.chat(
                model=JUDGE_MODEL,
                messages=[{"role": "system", "content": FAITH_SYSTEM},
                          {"role": "user", "content": user}],
                options={"temperature": 0.0, "num_predict": 1500,
                         "num_ctx": 8192})
            obj = parse_json_object(r["message"]["content"],
                                    required_keys=["claims"],
                                    list_recovery=True)
            if obj is not None and isinstance(obj["claims"], list):
                return obj
            time.sleep(1)
        except Exception as e:
            print(f"      faithfulness error (try {attempt+1}): {e}")
            time.sleep(2)
    return None


