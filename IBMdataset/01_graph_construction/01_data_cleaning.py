from sklearn.feature_extraction.text import TfidfVectorizer

def get_cluster_keywords(df, n_words=3):
    # Group text by cluster
    cluster_docs = df.groupby('cluster_id')['argument'].apply(lambda x: " ".join(x))

    # Run TF-IDF on these "cluster documents"
    vectorizer = TfidfVectorizer(stop_words='english')
    tfidf_matrix = vectorizer.fit_transform(cluster_docs)
    feature_names = vectorizer.get_feature_names_out()

    topic_names = {}
    for i, cid in enumerate(cluster_docs.index):
        if cid == -1:
            topic_names[cid] = "Noise/Unclassified"
            continue

        # Get top keywords for this cluster
        row = tfidf_matrix.getrow(i).toarray()[0]
        top_indices = row.argsort()[-n_words:][::-1]
        keywords = [feature_names[idx] for idx in top_indices]
        topic_names[cid] = "Topic: " + " & ".join(keywords).title()

    return topic_names

# Apply to your dataframe
