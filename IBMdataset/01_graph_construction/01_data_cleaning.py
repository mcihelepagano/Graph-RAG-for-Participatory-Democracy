import pandas as pd
import re
import unicodedata

def clean_ibm_text(text):
    if not isinstance(text, str):
        return ""

    # 1. Unicode Normalization (converts things like \xa0 to spaces)
    text = unicodedata.normalize('NFKD', text)

    # 2. Remove HTML artifacts and URLs
    text = re.sub(r'http[s]?://\S+', '', text)
    text = re.sub(r'<.*?>', '', text)

    # 3. Fix "Debater-specific" noise (e.g., specific ID tags if any)
    text = re.sub(r'\[\d+\]', '', text)

    # 4. Standardize Whitespace
    text = " ".join(text.split())

    return text

